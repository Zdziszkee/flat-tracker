import { createFileRoute } from "@tanstack/react-router";
import { json } from "@tanstack/react-start";
import { type SQL, sql } from "drizzle-orm";

import { REGIONS } from "#/crawler/regions";
import { db } from "#/db/index";
import { listings, transactions } from "#/db/schema";
import { makeDistrictMatcher } from "#/lib/powiat-districts";

/**
 * Voivodeship choropleth: per-powiat metrics joined onto the bundled OSM
 * admin_level=6 boundaries for every tracked voivodeship (Małopolska and
 * Śląsk).
 *
 * Assignment is coordinate-first: every listing/transaction with lat/lng is
 * dropped into its powiat by point-in-polygon (bbox prefiltered). Listings
 * without coordinates but with a district string are matched to a powiat by
 * normalized name (covers "Kraków", "Katowice" and the powiat names portals
 * put in the district field); everything else stays unassigned rather than
 * guessing.
 */

/**
 * Bounding box union of every tracked voivodeship, as SQL text. The numbers
 * come from the crawler region config (`src/crawler/regions.ts`), and the
 * boxes may overlap (Kraków-Częstochowa border), which is harmless for an OR
 * over rows. `src/db/region.ts` carries the same union as
 * `inTrackedRegions`, plus the matching partial index on `transactions`;
 * once that lands this constant goes away.
 */
const TRACKED_REGION_SQL = REGIONS.map(
	(r) =>
		`(lat between ${r.bbox.minLat} and ${r.bbox.maxLat} and lng between ${r.bbox.minLng} and ${r.bbox.maxLng})`,
).join(" or ");
const inTrackedRegions: SQL = sql.raw(TRACKED_REGION_SQL);

interface PowiatPoly {
	name: string;
	/** Voivodeship the powiat belongs to ("małopolskie" | "śląskie"). */
	voivodeship: string;
	/** Outer rings first, then holes; even-odd point-in-polygon. */
	rings: Array<Array<[number, number]>>; // [lon, lat]
	minLon: number;
	minLat: number;
	maxLon: number;
	maxLat: number;
}

/**
 * Boundary dataset (`#/data/region-powiats`, generated by
 * `bun run build:powiats`). Loaded lazily: this route is reachable from
 * the route tree, so a missing/broken dataset must degrade to "no
 * assignment" instead of 500-ing every page of the app.
 */
let polysCache: PowiatPoly[] | null = null;

async function loadPolys(): Promise<PowiatPoly[]> {
	if (polysCache) return polysCache;
	try {
		const { regionPowiats } = await import("#/data/region-powiats");
		polysCache = regionPowiats.map((f) => {
			const rings = f.geometry.coordinates as Array<Array<[number, number]>>;
			let minLon = Number.POSITIVE_INFINITY;
			let minLat = Number.POSITIVE_INFINITY;
			let maxLon = Number.NEGATIVE_INFINITY;
			let maxLat = Number.NEGATIVE_INFINITY;
			for (const ring of rings) {
				for (const [lon, lat] of ring) {
					if (lon < minLon) minLon = lon;
					if (lon > maxLon) maxLon = lon;
					if (lat < minLat) minLat = lat;
					if (lat > maxLat) maxLat = lat;
				}
			}
			return {
				name: f.properties.name,
				voivodeship: f.properties.voivodeship,
				rings,
				minLon,
				minLat,
				maxLon,
				maxLat,
			};
		});
	} catch (err) {
		console.error(
			"[/api/powiat-map] powiat boundaries unavailable; run `bun run build:powiats`",
			err,
		);
		polysCache = [];
	}
	return polysCache;
}

/** True when the point lies inside an odd number of the powiat's rings. */
function insidePowiat(lon: number, lat: number, p: PowiatPoly): boolean {
	let crossings = 0;
	for (const ring of p.rings) {
		if (pointInRing(lon, lat, ring)) crossings++;
	}
	return crossings % 2 === 1;
}

function pointInRing(
	lon: number,
	lat: number,
	ring: Array<[number, number]>,
): boolean {
	let inside = false;
	for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
		const [xi, yi] = ring[i];
		const [xj, yj] = ring[j];
		const intersect =
			yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;
		if (intersect) inside = !inside;
	}
	return inside;
}

/** district string -> powiat name (aliases + normalized exact/prefix match). */
function makeMatcherForPolys(polys: PowiatPoly[]) {
	return makeDistrictMatcher(polys.map((p) => p.name));
}

export const Route = createFileRoute("/api/powiat-map")({
	server: {
		handlers: {
			GET: async () => {
				const polys = await loadPolys();
				const powiatForDistrict = makeMatcherForPolys(polys);
				const metrics = new Map<
					string,
					{
						saleSum: number;
						saleN: number;
						saleCount: number;
						rentSum: number;
						rentN: number;
						rentCount: number;
					}
				>();
				const bucket = (name: string) => {
					let m = metrics.get(name);
					if (!m) {
						m = {
							saleSum: 0,
							saleN: 0,
							saleCount: 0,
							rentSum: 0,
							rentN: 0,
							rentCount: 0,
						};
						metrics.set(name, m);
					}
					return m;
				};

				// --- coordinate-first listing assignment ---
				// Plots ("działka", area > 500 m²) are excluded from sale
				// price/m² averages: a 630 m² plot at 120k zł would drag a
				// powiat's average down to nonsense (118 zł/m²).
				const rows = await db
					.select({
						lat: listings.lat,
						lng: listings.lng,
						district: listings.district,
						offerType: listings.offerType,
						pricePerM2: listings.pricePerM2,
						areaM2: listings.areaM2,
						title: listings.title,
					})
					.from(listings)
					.where(sql`${listings.isActive} = 1`)
					.all();

				const isPlot = (r: { areaM2: number | null; title: string | null }) =>
					(r.areaM2 ?? 0) > 500 ||
					(r.title?.toLowerCase().includes("działka") ?? false);

				for (const r of rows) {
					let name: string | null = null;
					if (r.lat != null && r.lng != null) {
						for (const p of polys) {
							if (
								r.lng < p.minLon ||
								r.lng > p.maxLon ||
								r.lat < p.minLat ||
								r.lat > p.maxLat
							)
								continue;
							if (insidePowiat(r.lng, r.lat, p)) {
								name = p.name;
								break;
							}
						}
					}
					if (!name) name = powiatForDistrict(r.district);
					if (!name) continue;

					const m = bucket(name);
					if (r.offerType === "sale") {
						m.saleCount++;
						if (r.pricePerM2 != null && r.pricePerM2 > 0 && !isPlot(r)) {
							m.saleSum += r.pricePerM2;
							m.saleN++;
						}
					} else if (r.offerType === "long_term_rental") {
						m.rentCount++;
						if (r.pricePerM2 != null) {
							m.rentSum += r.pricePerM2;
							m.rentN++;
						}
					}
				}

				// --- RCN transacted price/m² per powiat (all have coords) ---
				// Region-scoped so a national RCN drain never drags out-of-region
				// rows through the point-in-polygon loop.
				const txs = await db
					.select({
						lat: transactions.lat,
						lng: transactions.lng,
						pricePerM2: transactions.pricePerM2,
					})
					.from(transactions)
					.where(
						sql`${transactions.pricePerM2} is not null and ${transactions.lat} is not null and ${transactions.lng} is not null and ${inTrackedRegions}`,
					)
					.all();
				const rcn = new Map<string, { sum: number; n: number }>();
				for (const t of txs) {
					if (t.lat == null || t.lng == null) continue;
					for (const p of polys) {
						if (
							t.lng < p.minLon ||
							t.lng > p.maxLon ||
							t.lat < p.minLat ||
							t.lat > p.maxLat
						)
							continue;
						if (insidePowiat(t.lng, t.lat, p)) {
							const e = rcn.get(p.name) ?? { sum: 0, n: 0 };
							e.sum += t.pricePerM2 ?? 0;
							e.n += 1;
							rcn.set(p.name, e);
							break;
						}
					}
				}

				const features = polys.map((p) => {
					const m = metrics.get(p.name);
					const tx = rcn.get(p.name);
					const saleAvgM2 = m && m.saleN > 0 ? m.saleSum / m.saleN : null;
					const rentAvgM2 = m && m.rentN > 0 ? m.rentSum / m.rentN : null;
					const yieldPct =
						saleAvgM2 != null && rentAvgM2 != null && saleAvgM2 > 0
							? Number((((rentAvgM2 * 12) / saleAvgM2) * 100).toFixed(1))
							: null;
					return {
						name: p.name,
						voivodeship: p.voivodeship,
						saleCount: m?.saleCount ?? 0,
						saleAvgM2: saleAvgM2 != null ? Number(saleAvgM2.toFixed(0)) : null,
						rentCount: m?.rentCount ?? 0,
						rentAvgM2: rentAvgM2 != null ? Number(rentAvgM2.toFixed(1)) : null,
						yieldPct,
						rcnCount: tx?.n ?? 0,
						rcnAvgM2:
							tx && tx.n > 0 ? Number((tx.sum / tx.n).toFixed(0)) : null,
					};
				});

				return json({ features });
			},
		},
	},
});
